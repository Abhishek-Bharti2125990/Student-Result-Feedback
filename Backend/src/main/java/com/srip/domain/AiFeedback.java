package com.srip.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Lob;
import jakarta.persistence.Table;

import java.time.Instant;

/**
 * A generated feedback document, stored as JSON.
 *
 * <p>Persisting the result matters for more than speed: a model call is billed
 * and non-deterministic, so the feedback a parent was shown last week has to
 * stay retrievable exactly as it was written.
 */
@Entity
@Table(name = "ai_feedback")
public class AiFeedback {

    public enum Audience {
        STUDENT,
        TEACHER,
        PARENT
    }

    public enum Source {
        /** Generated by the Claude API. */
        CLAUDE,
        /** Generated locally by the rule-based writer (no API key configured). */
        FALLBACK
    }

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Null for TEACHER feedback, which is scoped to a class, not a student. */
    @Column(name = "student_id")
    private Long studentId;

    /** Set for TEACHER feedback; null for student- and parent-facing documents. */
    @Column(name = "class_name", length = 16)
    private String className;

    /** Null for a whole-history review rather than a single exam. */
    @Column(name = "exam_id")
    private Long examId;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private Audience audience;

    @Lob
    @Column(name = "payload_json", nullable = false)
    private String payloadJson;

    @Column(nullable = false, length = 64)
    private String model;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private Source source;

    @Column(name = "input_tokens")
    private Integer inputTokens;

    @Column(name = "output_tokens")
    private Integer outputTokens;

    @Column(name = "generated_at", nullable = false)
    private Instant generatedAt;

    protected AiFeedback() {
        // required by JPA
    }

    public AiFeedback(Long studentId, String className, Long examId, Audience audience, String payloadJson,
                      String model, Source source, Integer inputTokens, Integer outputTokens) {
        this.studentId = studentId;
        this.className = className;
        this.examId = examId;
        this.audience = audience;
        this.payloadJson = payloadJson;
        this.model = model;
        this.source = source;
        this.inputTokens = inputTokens;
        this.outputTokens = outputTokens;
        this.generatedAt = Instant.now();
    }

    public Long getId() {
        return id;
    }

    public Long getStudentId() {
        return studentId;
    }

    public String getClassName() {
        return className;
    }

    public Long getExamId() {
        return examId;
    }

    public Audience getAudience() {
        return audience;
    }

    public String getPayloadJson() {
        return payloadJson;
    }

    public String getModel() {
        return model;
    }

    public Source getSource() {
        return source;
    }

    public Integer getInputTokens() {
        return inputTokens;
    }

    public Integer getOutputTokens() {
        return outputTokens;
    }

    public Instant getGeneratedAt() {
        return generatedAt;
    }
}
