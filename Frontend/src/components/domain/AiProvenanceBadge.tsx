import { Bot, Clock, Sparkles } from 'lucide-react';
import { Badge } from '@/components/ui/Badge';
import { dateTime } from '@/lib/format';
import type { FeedbackSource } from '@/types/common';

interface AiProvenanceBadgeProps {
    source: FeedbackSource;
    model: string;
    generatedAt?: string;
    cached?: boolean;
    /** Hides the model name and timestamp, for a tight header. */
    compact?: boolean;
}

/**
 * Says who wrote the text next to it.
 *
 * This is not decoration. When no API key is configured the platform falls back
 * to a local rule-based writer, and a reader who assumes everything on the page
 * came from a model would be misled about both its quality and its cost. The
 * badge names the source and the exact model, every time.
 */
export function AiProvenanceBadge({
    source,
    model,
    generatedAt,
    cached = false,
    compact = false,
}: AiProvenanceBadgeProps) {
    const isClaude = source === 'CLAUDE';

    return (
        <div className="flex flex-wrap items-center gap-2">
            <Badge
                tone={isClaude ? 'violet' : 'slate'}
                icon={isClaude ? <Sparkles className="size-3" aria-hidden /> : <Bot className="size-3" aria-hidden />}
            >
                {source}
            </Badge>

            {!compact && (
                <span className="text-xs text-slate-500">
                    {isClaude ? 'Generated by' : 'Written locally by'}{' '}
                    <span className="font-medium text-slate-700">{model}</span>
                </span>
            )}

            {!compact && generatedAt && (
                <span className="inline-flex items-center gap-1 text-xs text-slate-400">
                    <Clock className="size-3" aria-hidden />
                    {dateTime(generatedAt)}
                    {cached && ' · stored'}
                </span>
            )}
        </div>
    );
}
